/** Canonical LotGuard walkthrough against real isolated services, no provider calls. */
import assert from "node:assert/strict";
import { expect } from "@playwright/test";
import path from "node:path";

export async function runEpsDemoUiTest({ page, base, visuals }) {
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(`${base}/ui/#cases`);
  const existingDrawer = page.getByRole('dialog', { name: 'Case detail' });
  if (await existingDrawer.isVisible()) await existingDrawer.getByRole('button', { name: 'Close', exact: true }).first().click();
  await expect(page.getByRole('button', { name: 'Load LotGuard demo', exact: true })).toBeVisible();
  const seeded = page.waitForResponse(r => r.url().endsWith('/demo/eps-b14') && r.request().method() === 'POST', { timeout: 180000 }).catch(e => e);
  await page.getByRole('button', { name: 'Load LotGuard demo', exact: true }).click();
  const response = await seeded;
  if (response instanceof Error) throw response;
  assert.equal(response.status(), 200);
  const fixture = await response.json();
  const drawer = page.locator('[role="dialog"]');
  await expect(drawer.getByText('Evidence recorded', { exact: true })).toBeVisible({ timeout: 15000 });
  await expect(drawer.getByRole('button', { name: 'Dismiss request', exact: true })).toHaveCount(0);
  const risk = page.getByTestId('lot-risk-panel');
  await expect(risk).toContainText('213');
  await expect(risk).toContainText('202');
  await expect(risk).toContainText('68 opened / routed');
  await expect(risk).toContainText('41 workshop bookings');
  await expect(risk).toContainText('9 confirmed fictional findings');
  await expect(risk).toContainText('82.0% accuracy · macro-F1 0.514');
  await page.screenshot({ path: path.join(visuals, 'lotguard-hero-readiness.png'), fullPage: true });
  await risk.evaluate(node => node.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: path.join(visuals, 'lotguard-risk-results.png'), fullPage: true });
  await drawer.getByText('Why High? · inherited review priority', { exact: true }).click();
  await expect(drawer).toContainText('Reported severity: Medium');
  await drawer.getByText('Photos & scan codes', { exact: true }).click();
  await expect(drawer.getByLabel('Select evidence case')).toContainText('★ Demo ·');
  await expect(drawer).toContainText('C0035');
  await expect(drawer.getByRole('img', { name: 'FICTIONAL_eps_B14_label.png' })).toBeVisible();
  await drawer.getByLabel('Select evidence case').evaluate(node => node.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: path.join(visuals, 'lotguard-hero-evidence.png'), fullPage: true });
  await drawer.getByText(/Follow-up draft · prepared/).click();
  await drawer.getByRole('button', { name: 'Send demo follow-up', exact: true }).click();
  await expect(drawer.getByText(/Simulated delivered ·/)).toBeVisible();
  await risk.getByRole('link', { name: 'Review approved English / Hindi warning and owner replies' }).click();
  await expect(page.getByLabel('LotGuard campaign results')).toContainText('202 owners who had never called');
  await page.getByText('Hindi warning · same reviewed scope', { exact: true }).click();
  await expect(page.locator('p[lang="hi"]').filter({ hasText: 'EPS बैच B14' }).first()).toBeVisible();
  await page.getByPlaceholder(/Search/).first().fill('EPS-CITY-011');
  await page.getByRole('row').filter({ hasText: 'EPS-CITY-011' }).getByRole('button').click();
  await expect(page.locator('.sc-detail')).toContainText('SYN-SLOT-011');
  await expect(page.locator('.sc-detail')).toContainText('Simulated notice · resolved');
  await page.locator('.sc-detail').getByText(/SYN-SLOT-011/).first().evaluate(node => node.scrollIntoView({ block: 'center' }));
  await page.screenshot({ path: path.join(visuals, 'lotguard-outreach-confirmation.png'), fullPage: true });
  await page.goto(`${base}/ui/#safety-campaigns?campaign=${fixture.campaign_id}&tab=evidence`);
  await expect(page.getByRole('heading', { name: 'Supplier corrective action', exact: true })).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export evidence ↗', exact: true }).click();
  const packet = await download;
  assert.match(packet.suggestedFilename(), /\.json$/);
  console.log('PASS: canonical LotGuard UI shows grounded hero readiness, capped inherited severity, real photo/code storage, 213/202/68/41/9 outcomes, sourced 82.0%/0.514 evaluation, simulated follow-up, Hindi notice, workshop confirmation and evidence export.');
}
