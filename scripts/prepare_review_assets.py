"""Publish static review JavaScript without weakening the app's CSP."""
import re
import hashlib
import json
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[1]
    target = root/"dashboard/public/review-scripts"
    target.mkdir(parents=True, exist_ok=True)
    for name, template in [("original-review.js", "defect_review.html"), ("evidence-review.js", "evidence_review.html"), ("reviewer-study.js", "reviewer_study.html")]:
        text = (root/"scripts/templates"/template).read_text()
        scripts = re.findall(r"<script>([\s\S]*?)</script>", text)
        if len(scripts) != 1:
            raise ValueError("Expected exactly one trusted UI script")
        (target/name).write_text("// Generated by scripts.prepare_review_assets from the review template.\n"+scripts[0]+"\n")
    # Update presentation only. Frozen review data, labels and sample hashes are
    # never rewritten or printed; no review is completed by this operation.
    evidence_template = (root/"scripts/templates/evidence_review.html").read_text()
    for name in ("development_review", "fuel_complaint_review", "recall_review"):
        source = root/"reports/defect/evidence_v1"/f"{name}.json"
        if not source.is_file():
            continue
        pack = json.loads(source.read_text())
        computed = hashlib.sha256(json.dumps({k: v for k, v in pack.items() if k != "sample_hash"}, sort_keys=True, ensure_ascii=False).encode()).hexdigest()
        if computed != pack.get("sample_hash"):
            raise ValueError("Frozen review data changed; refusing to render")
        source.with_suffix(".html").write_text(evidence_template.replace("__REVIEW_DATA__", json.dumps(pack, ensure_ascii=False).replace("<", "\\u003c")))
    study_source = root/"reports/hackathon/reviewer_study/study.json"
    if study_source.is_file():
        study = json.loads(study_source.read_text())
        computed = hashlib.sha256(json.dumps({k: v for k, v in study.items() if k != "study_hash"}, sort_keys=True, ensure_ascii=False).encode()).hexdigest()
        if computed != study.get("study_hash"):
            raise ValueError("Frozen study data changed; refusing to render")
        template = (root/"scripts/templates/reviewer_study.html").read_text()
        study_source.with_suffix(".html").write_text(template.replace("__STUDY_DATA__", json.dumps(study, ensure_ascii=False).replace("<", "\\u003c")))
    print("Prepared three static review scripts; inline CSP remains unchanged.")


if __name__ == "__main__": main()
